// ─── Scaled dashboard content ─────────────────────────────────────────────────
// DashboardContent's internals are all fixed-pixel (960px-wide layout) —
// render at natural size and scale to fill the SCREEN_W×SCREEN_H box the
// homography maps onto, same approach as the members page's phone demo.
const DASHBOARD_NATURAL_WIDTH = 960;

function ScaledDashboardContent() {
  const outerRef = useRef(null);
  const [scale, setScale] = useState(1);

  useLayoutEffect(() => {
    function measure() {
      if (!outerRef.current) return;
      const w = outerRef.current.offsetWidth;
      if (w > 0) setScale(w / DASHBOARD_NATURAL_WIDTH);
    }
    measure();
    window.addEventListener("resize", measure);
    return () => window.removeEventListener("resize", measure);
  }, []);

  return (
    <div
      ref={outerRef}
      style={{
        width: "100%",
        height: "100%",
        overflow: "hidden",
        // Same defensive clip as the outer homography screen div -- this
        // wrapper has its OWN scale() transform nested inside that one, and
        // the double transform stack is enough for composited children
        // (reveal-in transitions, willChange:transform overlays) to escape
        // just overflow:hidden even with the outer clip-path in place.
        clipPath: "inset(0)",
        WebkitClipPath: "inset(0)",
      }}
    >
      <div
        style={{
          width: DASHBOARD_NATURAL_WIDTH,
          transform: `scale(${scale})`,
          transformOrigin: "top left",
        }}
      >
        <DashboardContent />
      </div>
    </div>
  );
}

