// The screen area in this photo has a real dashboard screenshot baked into
// it. Our own live content is homography-mapped over it, but a Chromium
// rendering bug (a large img sibling + a steeply-tilted large matrix3d
// child can clip part of the transformed child -- reproduced and confirmed
// via isolated test cases, not fixable through recalibration) can leave a
// sliver uncovered. laptop_screen_blanked.jpg is the same photo with the
// screen region pre-painted over in the dashboard's own background color
// (generated by whiteout.cjs, since deleted), so any such gap shows neutral
// background instead of the original baked-in screenshot showing through.
import laptopImg from "../../assets/laptop_screen_blanked.jpg";
import { homography } from "../members/PhoneHeroDemo";

// ─────────────────────────────────────────────────────────────────────────────
// "Laptop in hand" guided tour — the organizations-page counterpart to the
// members page's PhoneHeroDemo, same technique: a real device photo with a
// homography-mapped live screen over its actual display. Corners calibrated
// by hand against laptop.jpg (2000x1364 reference scale) with an iterative
// debug-overlay pass -- not estimated from the photo alone.
// ─────────────────────────────────────────────────────────────────────────────
const LAPTOP_W = 2000;
const LAPTOP_H = 1364;
const SCREEN_W = 1280;
const SCREEN_H = 800;
// [tlX,tlY, trX,trY, blX,blY, brX,brY] -- recalibrated against a debug-quad
// overlay rendered at the exact production sizing (2000x1364, object-fit
// cover); the values inherited from the deleted first calibration pass were
// off by enough to reveal the photo's own baked-in screenshot around the
// edges (a "double dashboard" ghosting artifact). Locked in via a labeled
// coordinate-grid overlay + per-corner close-up crops, not eyeballing the
// full photo -- the perspective tilt makes that unreliable at this scale.
const CORNERS = [280, 565, 1145, 20, 325, 955, 1490, 845];
const SCREEN_TRANSFORM = homography(SCREEN_W, SCREEN_H, CORNERS);

